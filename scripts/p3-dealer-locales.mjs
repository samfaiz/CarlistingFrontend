const readJson = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : {});
const merge = (base, extra) => {
  const out = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    out[k] =
      v && typeof v === 'object' && !Array.isArray(v) ? merge(base?.[k] ?? {}, v) : v;
  }
  return out;
};

for (const locale of LOCALES) {
  const dealerFile = join(ROOT, locale, 'dealer.json');
  writeFileSync(dealerFile, `${JSON.stringify(merge(readJson(dealerFile), DEALER[locale]), null, 2)}\n`, 'utf8');
  const commonFile = join(ROOT, locale, 'common.json');
  writeFileSync(commonFile, `${JSON.stringify(merge(readJson(commonFile), COMMON[locale]), null, 2)}\n`, 'utf8');
}
console.log(`dealer.json + common workspace keys written for ${LOCALES.join(', ')}`);
